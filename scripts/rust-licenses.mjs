// Inventory exact registry versions in Cargo.lock using primary crates.io metadata.
// This intentionally covers the entire lockfile, not a target's linked closure.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const lockPath = 'src-tauri/Cargo.lock';
const reportPath = 'artifacts/rust-licenses.json';
const cachePath = 'artifacts/rust-license-cache.json';
const packages = readFileSync(lockPath, 'utf8').split('[[package]]').slice(1).map(text => ({
  name: text.match(/^name = "([^"]+)"/m)?.[1],
  version: text.match(/^version = "([^"]+)"/m)?.[1],
  source: text.match(/^source = "([^"]+)"/m)?.[1],
})).filter(p => p.source?.startsWith('registry+'));
mkdirSync('artifacts', { recursive: true });
let cached = [];
try { cached = JSON.parse(readFileSync(cachePath, 'utf8')); } catch { /* first run */ }
const cache = new Map(cached.map(row => [`${row.name}@${row.version}`, row]));
const refresh = process.argv.includes('--refresh');
const permissive = new Set(['MIT', 'MIT-0', '0BSD', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC', 'Zlib', 'Unicode-3.0', 'CC0-1.0', 'Unlicense']);

function hasPermissiveOption(expression) {
  // crates.io retains some pre-SPDX "MIT/Apache-2.0" notation.
  const tokens = expression.replace(/Apache-2\.0 WITH LLVM-exception/g, 'Apache-2.0').replaceAll('/', ' OR ').match(/\(|\)|AND|OR|[A-Za-z0-9.+-]+/g) ?? [];
  let cursor = 0;
  const atom = () => {
    if (tokens[cursor] === '(') { cursor++; const result = or(); if (tokens[cursor++] !== ')') throw new Error('unbalanced SPDX expression'); return result; }
    return permissive.has(tokens[cursor++]);
  };
  const and = () => { let result = atom(); while (tokens[cursor] === 'AND') { cursor++; const right = atom(); result = result && right; } return result; };
  const or = () => { let result = and(); while (tokens[cursor] === 'OR') { cursor++; const right = and(); result = result || right; } return result; };
  try { const result = or(); return cursor === tokens.length && result; } catch { return false; }
}

async function metadata(p) {
  const metadataSource = `https://crates.io/api/v1/crates/${p.name}/${encodeURIComponent(p.version)}`;
  for (let attempt = 0; attempt < 3; attempt++) {
    const response = await fetch(metadataSource, {
      headers: { 'User-Agent': 'OpenNovelReader-license-inventory/0.1 (https://github.com/Asahi12-26/open-novel-reader)' },
      signal: AbortSignal.timeout(30000),
    });
    if ((response.status === 429 || response.status >= 500) && attempt < 2) {
      const seconds = Math.min(10, Math.max(1, Number(response.headers.get('Retry-After')) || attempt + 1));
      await new Promise(resolve => setTimeout(resolve, seconds * 1000));
      continue;
    }
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const { version } = await response.json();
    if (!version || version.num !== p.version) throw new Error('locked version absent from primary registry metadata');
    return { ...p, license: version.license ?? null, metadataSource, sourceArchive: `https://crates.io/api/v1/crates/${p.name}/${encodeURIComponent(p.version)}/download` };
  }
  throw new Error('registry retry exhausted');
}

let next = 0;
const rows = [];
await Promise.all(Array.from({ length: 3 }, async () => {
  while (next < packages.length) {
    const p = packages[next++];
    const key = `${p.name}@${p.version}`;
    try {
      const row = !refresh && cache.get(key)?.license ? cache.get(key) : await metadata(p);
      rows.push(row); cache.set(key, row);
    } catch (error) { rows.push({ ...p, error: String(error) }); }
    await new Promise(resolve => setTimeout(resolve, 100));
  }
}));
rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const byLicense = {};
for (const row of rows) byLicense[row.license ?? 'UNKNOWN'] = (byLicense[row.license ?? 'UNKNOWN'] ?? 0) + 1;
const mplOnly = rows.filter(row => row.license === 'MPL-2.0');
const unresolved = rows.filter(row => row.error || !row.license || (!hasPermissiveOption(row.license) && row.license !== 'MPL-2.0'));
const report = {
  lockfile: lockPath,
  scope: 'All registry packages pinned by Cargo.lock, including build tools and other-platform dependencies; not the linked closure of either distributed binary.',
  registryPackages: packages.length,
  byLicense,
  mplOnly,
  unresolved,
  packages: rows,
};
writeFileSync(cachePath, JSON.stringify([...cache.values()], null, 2));
writeFileSync(reportPath, JSON.stringify(report, null, 2));
const noticeRows = rows.map(p => `| ${p.name} | ${p.version} | ${p.license ?? 'UNKNOWN'} | [source archive](${p.sourceArchive ?? `https://crates.io/api/v1/crates/${p.name}/${encodeURIComponent(p.version)}/download`}) |`);
writeFileSync('docs/RUST_DEPENDENCIES.md', [
  '# Locked Rust dependency inventory', '',
  'Generated by `node scripts/rust-licenses.mjs` from `src-tauri/Cargo.lock` and the primary crates.io version API. This covers all registry packages in the lockfile, including build tools and other-platform dependencies. It is not a claim that every listed crate is linked into the Windows or Android binaries.', '',
  'The source archives retain the upstream license texts and notices. See [THIRD_PARTY_NOTICES](../THIRD_PARTY_NOTICES.md) for license choices, MPL source availability and the limits of this metadata review.', '',
  '| Crate | Locked version | Upstream license expression | Exact upstream source |',
  '| --- | --- | --- | --- |', ...noticeRows, '',
].join('\n'));
console.log(JSON.stringify({ registryPackages: packages.length, mplOnly: mplOnly.map(p => `${p.name}@${p.version}`), unresolved: unresolved.map(p => `${p.name}@${p.version}: ${p.error ?? p.license}`), report: reportPath }, null, 2));
if (unresolved.length) process.exitCode = 1;
